#!/usr/bin/env bash
# Install (or remove) the yt-dlp widget in the KDE/GNOME application menu.
#
#   ./install.sh              install for the current user
#   ./install.sh --uninstall  remove the menu entry, icons and launcher
#
# Environment overrides:
#   YTDLP_GUI_PYTHON=/path/to/python   interpreter used by the launcher
#   SKIP_CACHE_UPDATE=1                do not refresh desktop/icon caches
set -euo pipefail

APP_ID="yt-dlp-gui"
APP_NAME="yt-dlp widget"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
BIN_HOME="${XDG_BIN_HOME:-$HOME/.local/bin}"
APPS_DIR="$DATA_HOME/applications"
ICON_ROOT="$DATA_HOME/icons/hicolor"
ASSET_DIR="$SCRIPT_DIR/yt_dlp_gui/assets/icons"
DESKTOP_FILE="$APPS_DIR/$APP_ID.desktop"
LAUNCHER="$BIN_HOME/$APP_ID"
WRAPPER_MARKER="# generated by yt-dlp-gui install.sh"

usage() {
    cat <<EOF
Usage: $0 [--uninstall] [--help]

Installs a KDE/GNOME menu entry and the yt-dlp-gui icons for the current user.

  -u, --uninstall   remove everything this script installed
  -h, --help        show this help

Files written:
  $DESKTOP_FILE
  $ICON_ROOT/<size>x<size>/apps/$APP_ID.png
  $LAUNCHER
EOF
}

refresh_caches() {
    [ "${SKIP_CACHE_UPDATE:-0}" = "1" ] && return 0
    # KDE caches rendered icon pixmaps by name; stale copies otherwise survive
    # an icon redesign even after the PNG files are replaced.
    rm -f "${XDG_CACHE_HOME:-$HOME/.cache}/icon-cache.kcache"
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
    fi
    if command -v gtk-update-icon-cache >/dev/null 2>&1; then
        gtk-update-icon-cache -f -t "$ICON_ROOT" >/dev/null 2>&1 || true
    fi
    if command -v kbuildsycoca6 >/dev/null 2>&1; then
        kbuildsycoca6 --noincremental >/dev/null 2>&1 ||
            kbuildsycoca6 >/dev/null 2>&1 || true
    elif command -v kbuildsycoca5 >/dev/null 2>&1; then
        kbuildsycoca5 --noincremental >/dev/null 2>&1 ||
            kbuildsycoca5 >/dev/null 2>&1 || true
    fi
}

uninstall() {
    rm -f "$DESKTOP_FILE"
    find "$ICON_ROOT" -path "*/apps/$APP_ID.png" -delete 2>/dev/null || true
    if [ -f "$LAUNCHER" ] && grep -qF "$WRAPPER_MARKER" "$LAUNCHER"; then
        rm -f "$LAUNCHER"
    fi
    rm -f "${XDG_CONFIG_HOME:-$HOME/.config}/autostart/$APP_ID.desktop"
    refresh_caches
    echo "Removed the $APP_NAME menu entry, icons, launcher and autostart file."
    echo "Your settings and download logs were kept."
}

pick_python() {
    if [ -n "${YTDLP_GUI_PYTHON:-}" ]; then
        if [ -x "$YTDLP_GUI_PYTHON" ]; then
            printf '%s' "$YTDLP_GUI_PYTHON"
            return 0
        fi
        local resolved
        resolved="$(command -v "$YTDLP_GUI_PYTHON" || true)"
        if [ -n "$resolved" ]; then
            printf '%s' "$resolved"
            return 0
        fi
        echo "error: YTDLP_GUI_PYTHON=$YTDLP_GUI_PYTHON is not executable" >&2
        return 1
    fi
    if [ -x "$SCRIPT_DIR/.venv/bin/python" ]; then
        printf '%s' "$SCRIPT_DIR/.venv/bin/python"
        return 0
    fi
    if command -v poetry >/dev/null 2>&1; then
        local env_python
        env_python="$(cd -- "$SCRIPT_DIR" && poetry env info --executable 2>/dev/null || true)"
        if [ -n "$env_python" ] && [ -x "$env_python" ]; then
            printf '%s' "$env_python"
            return 0
        fi
    fi
    command -v python3 || command -v python
}

install_menu() {
    if [ ! -d "$ASSET_DIR" ]; then
        echo "error: icon assets not found in $ASSET_DIR" >&2
        echo "       run: python3 scripts/generate_icons.py" >&2
        exit 1
    fi

    local python
    python="$(pick_python || true)"
    if [ -z "$python" ] || [ ! -x "$python" ]; then
        echo "error: no usable Python interpreter found (set YTDLP_GUI_PYTHON)" >&2
        exit 1
    fi
    if ! PYTHONPATH="$SCRIPT_DIR${PYTHONPATH:+:$PYTHONPATH}" \
        "$python" -c 'import PySide6, yt_dlp_gui' >/dev/null 2>&1; then
        echo "error: $python cannot import PySide6/yt_dlp_gui." >&2
        echo "       run 'poetry install' or install PySide6-Essentials first." >&2
        exit 1
    fi
    if ! command -v yt-dlp >/dev/null 2>&1; then
        echo "warning: yt-dlp is not on PATH; install it (e.g. 'sudo pacman -S yt-dlp')." >&2
    fi
    if ! command -v ffmpeg >/dev/null 2>&1; then
        echo "warning: ffmpeg is not on PATH; merging and MP3 extraction will fail." >&2
    fi

    mkdir -p "$APPS_DIR" "$BIN_HOME" "$ICON_ROOT"

    if [ -e "$LAUNCHER" ] && ! grep -qF "$WRAPPER_MARKER" "$LAUNCHER" 2>/dev/null; then
        echo "error: $LAUNCHER already exists and was not created by this script." >&2
        echo "       move it away or remove it, then re-run." >&2
        exit 1
    fi
    printf '%s\n' \
        '#!/usr/bin/env bash' \
        "$WRAPPER_MARKER" \
        "export PYTHONPATH=\"$SCRIPT_DIR\${PYTHONPATH:+:\$PYTHONPATH}\"" \
        "exec \"$python\" -m yt_dlp_gui \"\$@\"" \
        > "$LAUNCHER"
    chmod 755 "$LAUNCHER"

    local icon size
    shopt -s nullglob
    for icon in "$ASSET_DIR/$APP_ID-"*.png; do
        size="${icon##*/$APP_ID-}"
        size="${size%.png}"
        install -Dm644 "$icon" "$ICON_ROOT/${size}x${size}/apps/$APP_ID.png"
    done
    shopt -u nullglob

    cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=$APP_NAME
GenericName=Video downloader widget
Comment=Small always-on-top widget to download videos with yt-dlp
Exec="$LAUNCHER"
Icon=$APP_ID
Terminal=false
Categories=AudioVideo;Video;
Keywords=yt-dlp;youtube;download;video;widget;
StartupNotify=false
StartupWMClass=$APP_ID
EOF

    refresh_caches
    # Bump the desktop file so KDE re-reads its cached menu entry.
    touch "$DESKTOP_FILE"

    echo "Installed $APP_NAME:"
    echo "  menu entry: $DESKTOP_FILE"
    echo "  icons:      $ICON_ROOT/*/apps/$APP_ID.png"
    echo "  launcher:   $LAUNCHER"
    echo "Look for \"yt-dlp\" in the application menu."
}

case "${1:-}" in
    "" | --install) install_menu ;;
    -u | --uninstall) uninstall ;;
    -h | --help) usage ;;
    *)
        usage >&2
        exit 2
        ;;
esac
